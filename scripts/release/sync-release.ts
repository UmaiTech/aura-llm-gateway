/**
 * Release PR bookkeeping that release-plz can't do on its own.
 *
 * release-plz writes the CHANGELOG section for a release but only from
 * commits that touch a Rust crate, so frontend, docs and CI work never
 * reaches it. The public roadmap (apps/landing/src/lib/roadmap.ts) also has
 * to name the new release, or roadmap.test.ts fails the release PR.
 *
 * These functions are pure so they can be tested; sync-release-cli.ts runs
 * them against the repo. Both are idempotent: running them again on an
 * already synced release PR changes nothing.
 */

export const REPO = 'https://github.com/UmaiTech/aura-llm-gateway'

export interface ChangelogRelease {
  version: string
  date: string
}

/** The newest `## [x.y.z] - yyyy-mm-dd` heading in CHANGELOG.md. */
export function newestRelease(changelog: string): ChangelogRelease | undefined {
  const m = changelog.match(/^## \[(\d+\.\d+\.\d+)\] - (\d{4}-\d{2}-\d{2})\s*$/m)
  return m ? { version: m[1], date: m[2] } : undefined
}

export interface ChangelogEntry {
  group: string
  text: string
  pr?: number
}

// Mirrors the commit_parsers in cliff.toml, which release-plz uses.
const SKIPPED = [/^chore\((release|deps|pr|pull)\)/, /^chore: (release|sync) /]
const GROUPS: [RegExp, string][] = [
  [/^feat/, 'Features'],
  [/^fix/, 'Bug Fixes'],
  [/^doc/, 'Documentation'],
  [/^perf/, 'Performance'],
  [/^refactor/, 'Refactor'],
  [/^style/, 'Styling'],
  [/^test/, 'Testing'],
  [/^(chore|ci)/, 'Miscellaneous Tasks'],
  [/^revert/, 'Revert'],
]

/** A squash-merge subject like `feat(landing): add x (#12)` as a CHANGELOG entry. */
export function parseCommitSubject(subject: string): ChangelogEntry | undefined {
  if (SKIPPED.some((re) => re.test(subject))) return undefined
  const m = subject.match(/^(\w+)(?:\([^)]*\))?!?: (.+)$/)
  if (!m) return undefined
  const group = GROUPS.find(([re]) => re.test(m[1]))?.[1]
  if (!group) return undefined
  let text = m[2].trim()
  let pr: number | undefined
  const prMatch = text.match(/\s*\(#(\d+)\)$/)
  if (prMatch) {
    pr = Number(prMatch[1])
    text = text.slice(0, prMatch.index).trim()
  }
  return { group, text: text.charAt(0).toUpperCase() + text.slice(1), pr }
}

const bullet = (e: ChangelogEntry) => (e.pr ? `- ${e.text} ([#${e.pr}](${REPO}/pull/${e.pr}))` : `- ${e.text}`)
const normalize = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim()

/**
 * Add the commits release-plz left out of `version`'s CHANGELOG section.
 * A commit counts as present when its PR number or its text already appears.
 */
export function fillChangelogSection(changelog: string, version: string, subjects: string[]): string {
  const lines = changelog.split('\n')
  const start = lines.findIndex((l) => l.startsWith(`## [${version}] - `))
  if (start === -1) return changelog
  let end = lines.findIndex((l, i) => i > start && l.startsWith('## ['))
  if (end === -1) end = lines.length
  const section = lines.slice(start + 1, end)

  const footerAt = section.findIndex((l) => l.startsWith('<!-- generated by git-cliff'))
  const body = footerAt === -1 ? section : section.slice(0, footerAt)
  const footer = footerAt === -1 ? [] : section.slice(footerAt)

  const groups = new Map<string, string[]>()
  let current: string | undefined
  for (const line of body) {
    const heading = line.match(/^### (.+)$/)
    if (heading) {
      current = heading[1]
      groups.set(current, groups.get(current) ?? [])
    } else if (current && line.trim()) {
      groups.get(current)!.push(line)
    }
  }

  const existing = [...groups.values()].flat().join('\n')
  const seenPrs = new Set([...existing.matchAll(/#(\d+)/g)].map((m) => Number(m[1])))
  const seenText = normalize(existing)
  let added = 0
  for (const subject of subjects) {
    const entry = parseCommitSubject(subject)
    if (!entry) continue
    if (entry.pr ? seenPrs.has(entry.pr) : seenText.includes(normalize(entry.text))) continue
    if (!groups.has(entry.group)) groups.set(entry.group, [])
    groups.get(entry.group)!.push(bullet(entry))
    if (entry.pr) seenPrs.add(entry.pr)
    added++
  }
  if (added === 0) return changelog

  const rebuilt = ['']
  for (const name of [...groups.keys()].sort()) rebuilt.push(`### ${name}`, '', ...groups.get(name)!, '')
  rebuilt.push(...(footer.length ? footer : ['']))
  return [...lines.slice(0, start + 1), ...rebuilt, ...lines.slice(end)].join('\n')
}

export interface RoadmapSync {
  version: string
  date: string
  /** Every `v*` git tag. */
  tags: Set<string>
  /** Short SHA of the main commit the release is cut from. */
  revision: string
}

/**
 * Put a release into roadmap.ts: list it in RELEASES, mark versions whose tag
 * now exists as tagged, move every merged-unreleased item into it, and record
 * the reconciliation. Expects the layout roadmap.ts uses today: one release
 * per line in RELEASES, and top-level ROADMAP items opened by `  {` and closed
 * by `  },` on their own lines.
 */
export function syncRoadmap(source: string, { version, date, tags, revision }: RoadmapSync): string {
  let lines = source.split('\n')

  const releasesAt = lines.findIndex((l) => l.startsWith('export const RELEASES: Release[] = ['))
  if (releasesAt === -1) throw new Error('roadmap.ts: RELEASES not found')
  const releaseLine = /^ {2}\{ version: '([\d.]+)', date: '([\d-]+)', tagged: (true|false) \},$/
  const listed = lines.some((l) => releaseLine.exec(l)?.[1] === version)
  if (!listed) {
    lines.splice(releasesAt + 1, 0, `  { version: '${version}', date: '${date}', tagged: ${tags.has(`v${version}`)} },`)
  }
  lines = lines.map((l) => {
    const m = releaseLine.exec(l)
    return m && m[3] === 'false' && tags.has(`v${m[1]}`) ? l.replace('tagged: false', 'tagged: true') : l
  })

  const roadmapAt = lines.findIndex((l) => l.startsWith('export const ROADMAP: RoadmapItem[] = ['))
  if (roadmapAt === -1) throw new Error('roadmap.ts: ROADMAP not found')
  const moved: string[] = []
  for (let i = roadmapAt + 1; i < lines.length; i++) {
    if (lines[i] === '];') break
    if (lines[i] !== '  {') continue
    const close = lines.findIndex((l, j) => j > i && l === '  },')
    if (close === -1) throw new Error(`roadmap.ts: item at line ${i + 1} is not closed by "  },"`)
    const block = lines.slice(i, close + 1)
    if (!block.includes("    status: 'merged-unreleased',")) continue
    moved.push(
      `  released('${version}', {`,
      ...block
        .slice(1, -1)
        .filter((l) => l !== "    status: 'merged-unreleased',")
        .map((l) => l.replace(/\bUNRELEASED\b/g, `changelogLink('${version}', '${date}')`)),
      '  }),',
    )
    lines.splice(i, close - i + 1)
    i--
  }

  const mergedAt = lines.findIndex((l, i) => i > roadmapAt && l.includes('── Merged to main'))
  lines = lines.filter((l, i) => !(i > roadmapAt && /^ {2}\/\/ \(none: everything merged so far shipped in v[\d.]+\)$/.test(l)))
  const releasedAt = lines.findIndex((l, i) => i > roadmapAt && l.includes('── Released'))
  if (releasedAt === -1) throw new Error('roadmap.ts: "── Released" marker not found in ROADMAP')
  lines.splice(releasedAt + 1, 0, ...moved)
  if (mergedAt !== -1) {
    const between = lines.slice(mergedAt + 1, lines.findIndex((l, i) => i > mergedAt && l.includes('── Released')))
    if (!between.some((l) => l.trim() && !l.trim().startsWith('//'))) {
      lines.splice(mergedAt + 1, 0, `  // (none: everything merged so far shipped in v${version})`)
    }
  }

  return lines
    .join('\n')
    .replace(/(export const RECONCILED = \{\n {2}date: ')[\d-]+(')/, `$1${date}$2`)
    .replace(/(\n {2}revision: ')[0-9a-f]+(',)/, `$1${revision}$2`)
}

/** Keep the "Latest shipped" line in RoadmapPage.tsx's docstring current. */
export function syncRoadmapPageDoc(source: string, { version, date }: ChangelogRelease): string {
  return source.replace(/^( \* Latest shipped: )v[\d.]+ \([\d-]+\)$/m, `$1v${version} (${date})`)
}
